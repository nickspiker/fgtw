/// The release key's public bundle, every scheme.
pub fn release_bundle() -> KeyBundle {
    KeyBundle::from_bytes(&RELEASE_BUNDLE).expect("the pinned release bundle parses")
}

/// The header slots a release document reserves: one egg per scheme (`VsfBuilder::signed_only_eggs(ke(RELEASE_ED25519), &release_slots())`).
pub fn release_slots() -> Vec<(u8, usize)> {
    crate::pq::reserve_eggs(RELEASE_MASK)
}

/// Is `doc` a VSF document signed by the release key, with every egg present and verifying?
pub fn verify_release(doc: &[u8]) -> Result<(), String> {
    verify_signed_by(doc, &RELEASE_ED25519, &release_bundle()).map_err(|e| alloc::format!("release key: {e}"))
}

/// The rule [`verify_release`] applies, for any pinned key: the header's key is `ed`, and an egg for every scheme verifies against `bundle` — public so an installer checks a developer's kist against that developer's pinned bundle the same way (ferros, 2026-11-10).
pub fn verify_signed_by(doc: &[u8], ed: &[u8; 32], bundle: &KeyBundle) -> Result<(), String> {
    let (signer, eggs, file_hash) = vsf::verification::header_eggs(doc)?;
    if signer != *ed {
        return Err("signed: not signed by the expected key".into());
    }
    if !verify_eggs(&eggs, bundle, &file_hash, RELEASE_MASK) {
        return Err("signed: the key's eggs do not all verify".into());
    }
    Ok(())
}

/// Sign a document whose header was reserved with [`release_slots`]: every scheme signs the file hash.
#[cfg(feature = "sign")]
pub fn sign_release(unsigned: Vec<u8>, key: &crate::pq::SigningBundle) -> Result<Vec<u8>, String> {
    use crate::pq::FleetSigner;
    vsf::verification::sign_file_with(unsigned, |file_hash| key.eggs(file_hash, RELEASE_MASK))
}

#[cfg(all(test, feature = "sign"))]
mod tests {
    use super::*;
    use crate::pq::{FleetSigner, SigningBundle};
    use vsf::VsfType;

    /// A document signed by `key` with the release slots.
    fn signed_doc(key: &SigningBundle) -> Vec<u8> {
        let unsigned = vsf::VsfBuilder::new()
            .creation_time_oscillations(1)
            .signed_only_eggs(VsfType::ke(key.keypair().public.to_bytes().to_vec()), &release_slots())
            .add_section("release_notice", vec![("channel".to_string(), VsfType::a(vsf::types::Ascii::lit("release")))])
            .build()
            .unwrap();
        sign_release(unsigned, key).unwrap()
    }

    /// The pinned bundle parses, holds every scheme, and its Ed25519 half is the key every Photon pins.
    #[test]
    fn the_pin_is_whole() {
        let b = release_bundle();
        assert_eq!(b.ed25519(), RELEASE_ED25519);
        assert_eq!(b.mask(), RELEASE_MASK);
    }

    /// Signed with all three eggs it verifies; with one egg stripped, or by another key, it does not.
    #[test]
    fn every_egg_or_nothing() {
        let key = SigningBundle::release(&[7u8; 32]);
        let ed = key.keypair().public.to_bytes();
        let doc = signed_doc(&key);
        assert!(verify_signed_by(&doc, &ed, &key.public()).is_ok());
        let other = SigningBundle::release(&[8u8; 32]);
        assert!(verify_signed_by(&doc, &ed, &other.public()).is_err(), "another key's bundle");
        assert!(verify_release(&doc).is_err(), "not the real release key");
        let ed_only = vsf::VsfBuilder::new()
            .creation_time_oscillations(1)
            .signed_only_eggs(VsfType::ke(ed.to_vec()), &crate::pq::reserve_eggs(scheme::MASK_BASE))
            .add_section("release_notice", vec![])
            .build()
            .unwrap();
        let ed_only = vsf::verification::sign_file_with(ed_only, |h| key.eggs(h, scheme::MASK_BASE)).unwrap();
        assert!(verify_signed_by(&ed_only, &ed, &key.public()).is_err(), "one egg is not enough");
    }

    /// A developer's bundle signs and verifies like the release key's, and its post-quantum halves belong to its name: the same seed under another name, or as the release key, is another key.
    #[test]
    fn developer_bundles_are_their_own_keys() {
        let seed = [5u8; 32];
        let dev = SigningBundle::developer(&seed, "TEST_DEVELOPER");
        let ed = dev.keypair().public.to_bytes();
        assert!(verify_signed_by(&signed_doc(&dev), &ed, &dev.public()).is_ok());
        assert_eq!(SigningBundle::developer(&seed, "TEST_DEVELOPER").public(), dev.public(), "stable");
        assert_ne!(SigningBundle::developer(&seed, "OTHER_DEVELOPER").public(), dev.public());
        assert_ne!(SigningBundle::release(&seed).public(), dev.public());
        assert_eq!(SigningBundle::release(&seed).public().ed25519(), dev.public().ed25519(), "the Ed25519 half is the seed either way");
    }
}
