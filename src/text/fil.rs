// Filipino: the translation of en.rs, the reference.
// Photon's arms are Photon's own Filipino (photon 9a93f16c, src/ui/lang/fil.rs); where Photon falls back to English (SelectedDevice, SelectedBy and the four fgtw.org lines) the Filipino is written here in Photon's vocabulary (armada, pagkakakilanlan, device, ibigkis, aprubahan, tanggihan, mga salita). ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Magdagdag ng device"),
        Msg::TapNearby => o.write_str("o pindutin ang malapit na device na humihiling sumali:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} malapit"),
        Msg::TypeWords => o.write_str("I-type ang mga salitang ipinapakita ng bagong device"),
        Msg::InvalidWord(w) => write!(o, "hindi isa sa mga salita ang '{w}'"),
        Msg::WaitingForDevice => o.write_str("Hinihintay ang bagong device\u{2026} dapat ipinapakita na nito ang mga salita nito"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} na device ang humihiling sumali: i-type ang mga salita ng hawak mo"),
        Msg::NoMatchingDevice(bad) => write!(o, "walang device na humihiling sumali na tumutugma sa '{bad}'"),
        Msg::MatchingDevice(name) => write!(o, "tinutugma ang {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "tinutugma\u{2026} ({shown} na device)"),
        Msg::Preparing => o.write_str("Inihahanda\u{2026}"),
        Msg::NoFleetKey => o.write_str("Wala pa sa device na ito ang susi ng armada.\nGawin ito mula sa isa pang device mo."),
        Msg::NoDeviceKey => o.write_str("Hindi pa handa ang susi ng device na ito. Subukan ulit maya-maya."),
        Msg::AddingDevice(name) => write!(o, "Idinadagdag ang {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Naidagdag ang device \u{221a}"),
        Msg::JoinContended => o.write_str("Higit sa isang device ang humihiling sumali, kaya ang device lang na katabi nito ang maidadagdag ngayon, sa Bluetooth o NFC. Kung isa lang ang idinadagdag mo, may ibang nakakaalam ng handle mo."),
        Msg::AddFromSignedIn => o.write_str("Idagdag ang device na ito mula sa isang device na sa iyo na:"),
        Msg::AddDevicePill => o.write_str("Magdagdag ng device"),
        Msg::SelectedDevice(name) => write!(o, "Napili: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Matingkad na berde na ba ang bago mong device?"),
        Msg::YesPill => o.write_str("Oo"),
        Msg::NoPill => o.write_str("Hindi"),
        Msg::AddLookFgtw => o.write_str("Wala sa malapit? Maghanap sa fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Naghahanap din sa fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("may device sa network na ito na humihiling sumali"),
        Msg::AddAsking => o.write_str("magdagdag ng device: mga device na humihiling sumali"),
        Msg::AddSelected => o.write_str("magdagdag ng device: napili"),
        Msg::AddingToFleet => o.write_str("idinadagdag ito sa armada"),
        Msg::HandingKey => o.write_str("ibinibigay dito ang susi ng armada"),
        Msg::Added => o.write_str("naidagdag"),
        Msg::AddingFailed => o.write_str("nabigo ang pagdagdag"),
        Msg::CandAdded(name) => write!(o, "{name}  naidagdag"),
        Msg::CandNearby(name) => write!(o, "{name}  malapit: pindutin para piliin"),
        Msg::CandNotNearby(name) => write!(o, "{name}  hindi malapit: i-type ang mga salita nito"),
        Msg::OpenPhotonJoin => o.write_str("buksan sa device ang screen ng pagsali ng Photon"),
        Msg::TypeItsWordsPill => o.write_str("i-type ang mga salita nito"),
        Msg::HoldTogether => o.write_str("o pagdikitin ang dalawang device: sasali ito agad"),
        Msg::DonePill => o.write_str("tapos"),
        Msg::ClosePill => o.write_str("isara"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Pinili ng {name}"),
        Msg::JoinerSelected => o.write_str("Napili!"),
        Msg::JoinerConfirmOther => o.write_str("Kumpirmahin sa kabilang device mo para matapos."),
        Msg::LaunchJoinConfirmNote => o.write_str("Sa device na iyon mo kukumpirmahin ang pagdagdag."),
        Msg::JoinAskFgtw => o.write_str("Wala sa malapit ang mga device ko: humiling sa fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Humiling na sa fgtw.org: i-type ang mga salita sa kabilang device mo"),
        Msg::HandlesDontMatch => o.write_str("hindi magkatugma ang dalawa\nayusin ang pangalan at subukan ulit"),
        Msg::DeviceBrandedHint => o.write_str("Nakarehistro pa ang hardware na ito sa ibang armada.\nMapapalaya ito ng may-ari nito gamit ang Pakawalan sa pahina nilang Armada."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Gumamit ng dati mong device para ibigkis ang device na ito sa armada mo."),
        Msg::WaitingFleetKeys => o.write_str("Hinihintay ang mga susi ng armada."),
        Msg::BoundWaitingKeys => o.write_str("Nakabigkis na sa armada mo.\nHinihintay ang mga susi nito."),
        Msg::DeniedBoundOther => o.write_str("Tinanggihan. Nakabigkis ang device na ito sa ibang pagkakakilanlan."),
        Msg::OwnedByOther => o.write_str("Pag-aari ng ibang pagkakakilanlan ang device na ito.\nAng armada lang nito ang makapagpapakawala rito."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("ang device na ito"),
        Msg::ADevice => o.write_str("isang device"),
        Msg::TheDevice => o.write_str("ang device"),
        Msg::OneOfYourDevices => o.write_str("isa sa mga device mo"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  ang device na ito"),
        Msg::MemberNearby(name) => write!(o, "{name}  malapit"),
        Msg::NoIdentityHere => o.write_str("walang pagkakakilanlan dito"),
        Msg::JoiningConfirm => o.write_str("sumasali: kumpirmahin sa isa sa mga device mo"),
        Msg::InFleetWaitingKey => o.write_str("nasa armada, hinihintay ang susi nito"),
        Msg::InFleet => o.write_str("nasa armada"),
        Msg::LeavingFleet => o.write_str("umaalis sa armada"),
        Msg::NewIdentityNoFleet => o.write_str("bagong pagkakakilanlan: wala pang armadang may hawak nito"),
        Msg::HandleHasOtherFleet => o.write_str("may armada ng ibang pagkakakilanlan ang handle na ito"),
        Msg::NoVerdict => o.write_str("walang hatol: walang sumasagot"),
        Msg::LookingUp => o.write_str("hinahanap ang pagkakakilanlan"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "humihiling ang {name} na umalis sa armada mo. Aprubahan ito sa Mga Setting → Armada."),
        Msg::DepartRequestLine(name) => write!(o, "Humihiling ang {name} na umalis sa armada mo."),
        Msg::DepartFreesHardware => o.write_str("Kapag inaprubahan, buburahin ito at mapapalaya ang hardware nito para sumali sa kahit anong armada."),
        Msg::DepartKeepsHardware => o.write_str("Kapag inaprubahan, buburahin ito.\nMananatiling nakarehistro sa armada mo ang hardware nito."),
        Msg::DepartApprovePill => o.write_str("Aprubahan"),
        Msg::DepartDenyPill => o.write_str("Tanggihan"),
        Msg::DepartDeniedHere(name) => write!(o, "Tinanggihan. Mananatili ang {name} sa armada mo."),
        Msg::DepartComplete(n) => write!(o, "Umalis na ang {n} sa armada mo.\nMalaya na ang hardware nito."),
        Msg::FleetSignedOut(name) => write!(o, "umalis ang {name} sa armada."),
        Msg::DepartReleasePending(n) => write!(o, "Umalis na ang {n} sa armada mo, pero hindi napalaya ang hardware nito.\nPindutin ang Pakawalan sa retiradong hanay nito para subukan ulit."),
        Msg::DeviceReleased(name) => write!(o, "Napakawalan na ang {name}.\nPuwede na itong sumali sa kahit anong armada."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("kapag tinanggihan, mananatili ito sa armada mo"),
        Msg::DepartApproveAgainPill => o.write_str("aprubahan ulit: hindi naipadala ang huli"),
        Msg::DepartApproving => o.write_str("inaaprubahan"),
        Msg::DepartApproved => o.write_str("naaprubahan: aalis na ito sa armada mo"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Hinihiling sa iba mo pang device na payagang umalis ang isang ito. Aprubahan sa alinman sa kanila."),
        Msg::DepartDenied => o.write_str("Tinanggihan ng isa sa mga device mo ang hiling na ito, kaya mananatili ang device na ito sa armada mo. Pindutin ang Pakawalan para humiling ulit."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "pindutin ulit: alisin ang device na ito" } else { "alisin ang device na ito" }),
        Msg::DepartAsking => o.write_str("hinihiling ng device na ito sa armada mo na pakawalan ito"),
        Msg::DepartSending => o.write_str("ipinapadala ang hiling sa mga device mo"),
        Msg::DepartTapHint => o.write_str("aprubahan o tanggihan sa alinman sa iba mo pang device,\no idikit ang isa sa kanila sa device na ito"),
        Msg::DepartThen => o.write_str("kapag naaprubahan, buburahin dito ang mga gamit mo\nat magre-restart ito; kinakansela ng balik ang pag-alis"),
        Msg::DepartDeniedOn(name) => write!(o, "tinanggihan ang pag-alis sa {name}"),
        Msg::DepartNotStarted => o.write_str("hindi nagsimula ang pag-alis"),
    }
}
