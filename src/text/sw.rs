// Swahili (Kiswahili): an exhaustive match over the same messages as en.rs (the reference).
// Photon's arms are Photon's Swahili (photon 9a93f16c, src/ui/lang/sw.rs); ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
// Photon's sw.rs falls back to English for SelectedDevice, SelectedBy, JoinAskFgtw, JoinAskedFgtw, AddLookFgtw and AddLookingFgtw, so those six are translated here from Photon's English.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Ongeza kifaa"),
        Msg::TapNearby => o.write_str("au gusa kifaa kilicho karibu kinachoomba kujiunga:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} karibu"),
        Msg::TypeWords => o.write_str("Andika maneno yanayoonyeshwa kwenye kifaa kipya"),
        Msg::InvalidWord(w) => write!(o, "'{w}' si mojawapo ya maneno"),
        Msg::WaitingForDevice => o.write_str("Inasubiri kifaa kipya\u{2026} kinapaswa kuwa kinaonyesha maneno yake"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "vifaa {shown} vinaomba kujiunga: andika maneno ya kile kilicho mkononi mwako"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' hailingani na kifaa chochote kinachoomba kujiunga"),
        Msg::MatchingDevice(name) => write!(o, "inalinganisha {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "inalinganisha\u{2026} (vifaa {shown})"),
        Msg::Preparing => o.write_str("Inaandaa\u{2026}"),
        Msg::NoFleetKey => o.write_str("Kifaa hiki bado hakina ufunguo wa kundi.\nFanya hivi kutoka kifaa kingine chako."),
        Msg::NoDeviceKey => o.write_str("Ufunguo wa kifaa hiki bado haujawa tayari. Jaribu tena baada ya muda kidogo."),
        Msg::AddingDevice(name) => write!(o, "Inaongeza {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Kifaa kimeongezwa \u{221a}"),
        Msg::JoinContended => o.write_str("Zaidi ya kifaa kimoja vinaomba kujiunga, kwa hiyo sasa kifaa kilicho kando ya hiki pekee ndicho kinaweza kuongezwa, kwa Bluetooth au NFC. Kama unaongeza kimoja tu, mtu mwingine anajua handle yako."),
        Msg::AddFromSignedIn => o.write_str("Ongeza kifaa hiki kutoka kifaa ambacho tayari ni chako:"),
        Msg::AddDevicePill => o.write_str("Ongeza kifaa"),
        Msg::SelectedDevice(name) => write!(o, "Kimechaguliwa: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Je, kifaa chako kipya ni kijani angavu?"),
        Msg::YesPill => o.write_str("Ndiyo"),
        Msg::NoPill => o.write_str("Hapana"),
        Msg::AddLookFgtw => o.write_str("Hakiko karibu? Tafuta kupitia fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Inatafuta pia kupitia fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("kifaa kwenye mtandao huu kinaomba kujiunga"),
        Msg::AddAsking => o.write_str("ongeza kifaa: vifaa vinavyoomba kujiunga"),
        Msg::AddSelected => o.write_str("ongeza kifaa: kimechaguliwa"),
        Msg::AddingToFleet => o.write_str("kinaongezwa kundini"),
        Msg::HandingKey => o.write_str("kinapewa ufunguo wa kundi"),
        Msg::Added => o.write_str("kimeongezwa"),
        Msg::AddingFailed => o.write_str("kuongeza kumeshindikana"),
        Msg::CandAdded(name) => write!(o, "{name}  kimeongezwa"),
        Msg::CandNearby(name) => write!(o, "{name}  karibu: gusa ili kuchagua"),
        Msg::CandNotNearby(name) => write!(o, "{name}  si karibu: andika maneno yake"),
        Msg::OpenPhotonJoin => o.write_str("fungua skrini ya kujiunga ya Photon kwenye kifaa"),
        Msg::TypeItsWordsPill => o.write_str("andika maneno yake"),
        Msg::HoldTogether => o.write_str("au shikilia vifaa viwili pamoja: kinajiunga mara moja"),
        Msg::DonePill => o.write_str("maliza"),
        Msg::ClosePill => o.write_str("funga"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Kimechaguliwa na {name}"),
        Msg::JoinerSelected => o.write_str("Kimechaguliwa!"),
        Msg::JoinerConfirmOther => o.write_str("Thibitisha kwenye kifaa chako kingine ili kumaliza."),
        Msg::LaunchJoinConfirmNote => o.write_str("Utathibitisha kuongezwa kwenye kifaa hicho."),
        Msg::JoinAskFgtw => o.write_str("Vifaa vyangu haviko karibu: omba kupitia fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Imeombwa kupitia fgtw.org: andika maneno kwenye kifaa chako kingine"),
        Msg::HandlesDontMatch => o.write_str("hayo mawili hayalingani\nsahihisha jina na ujaribu tena"),
        Msg::DeviceBrandedHint => o.write_str("Maunzi haya bado yamesajiliwa kwenye kundi lingine.\nMmiliki wake anaweza kuyaachia kwa Achia kwenye ukurasa wake wa Kundi."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Tumia kifaa ulicho nacho tayari kufunga kifaa hiki kwenye kundi lako."),
        Msg::WaitingFleetKeys => o.write_str("Kinasubiri funguo za kundi."),
        Msg::BoundWaitingKeys => o.write_str("Kimefungwa kwenye kundi lako.\nKinasubiri funguo zake."),
        Msg::DeniedBoundOther => o.write_str("Imekataliwa. Kifaa hiki kimefungwa kwa utambulisho mwingine."),
        Msg::OwnedByOther => o.write_str("Kifaa hiki ni cha utambulisho mwingine.\nKundi lake pekee linaweza kukiachilia."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("kifaa hiki"),
        Msg::ADevice => o.write_str("kifaa"),
        Msg::TheDevice => o.write_str("kifaa hicho"),
        Msg::OneOfYourDevices => o.write_str("kimoja cha vifaa vyako"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  kifaa hiki"),
        Msg::MemberNearby(name) => write!(o, "{name}  karibu"),
        Msg::NoIdentityHere => o.write_str("hakuna utambulisho hapa"),
        Msg::JoiningConfirm => o.write_str("inajiunga: thibitisha kwenye kimoja cha vifaa vyako"),
        Msg::InFleetWaitingKey => o.write_str("kiko kundini, kinasubiri ufunguo wake"),
        Msg::InFleet => o.write_str("kiko kundini"),
        Msg::LeavingFleet => o.write_str("kinaondoka kundini"),
        Msg::NewIdentityNoFleet => o.write_str("utambulisho mpya: bado hakuna kundi linalouhifadhi"),
        Msg::HandleHasOtherFleet => o.write_str("handle hii ina kundi la utambulisho mwingine"),
        Msg::NoVerdict => o.write_str("hakuna uamuzi: hakuna kinachojibu"),
        Msg::LookingUp => o.write_str("inatafuta utambulisho"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} kinaomba kuondoka kundini kwako. Idhinisha katika Mipangilio → Kundi."),
        Msg::DepartRequestLine(name) => write!(o, "{name} kinaomba kuondoka kundini kwako."),
        Msg::DepartFreesHardware => o.write_str("Kuidhinisha hukifuta na kuachia maunzi yake ili yajiunge na kundi lolote."),
        Msg::DepartKeepsHardware => o.write_str("Kuidhinisha hukifuta.\nMaunzi yake yanabaki yamesajiliwa kwenye kundi lako."),
        Msg::DepartApprovePill => o.write_str("Idhinisha"),
        Msg::DepartDenyPill => o.write_str("Kataa"),
        Msg::DepartDeniedHere(name) => write!(o, "Imekataliwa. {name} kinabaki kundini kwako."),
        Msg::DepartComplete(n) => write!(o, "{n} kimeondoka kwenye kundi lako.\nMaunzi yake yako huru."),
        Msg::FleetSignedOut(name) => write!(o, "{name} kimeondoka kundini."),
        Msg::DepartReleasePending(n) => write!(o, "{n} kimeondoka kwenye kundi lako, lakini maunzi yake hayakuachiliwa.\nBonyeza Achia kwenye safu yake iliyostaafu ili kujaribu tena."),
        Msg::DeviceReleased(name) => write!(o, "{name} kimeachiliwa.\nSasa kinaweza kujiunga na kundi lolote."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("kukataa kunakibakiza kundini kwako"),
        Msg::DepartApproveAgainPill => o.write_str("idhinisha tena: idhini ya mwisho haikutoka"),
        Msg::DepartApproving => o.write_str("inaidhinisha"),
        Msg::DepartApproved => o.write_str("imeidhinishwa: kinaondoka kundini kwako"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Inaomba vifaa vyako vingine viruhusu hiki kiondoke. Idhinisha kwenye chochote kati yake."),
        Msg::DepartDenied => o.write_str("Kimoja cha vifaa vyako kimekataa ombi hili, kwa hiyo kifaa hiki kinabaki kundini kwako. Bonyeza Achia kuomba tena."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "gusa tena: ondoa kifaa hiki" } else { "ondoa kifaa hiki" }),
        Msg::DepartAsking => o.write_str("kifaa hiki kinaomba kundi lako likiachilie"),
        Msg::DepartSending => o.write_str("inatuma ombi kwa vifaa vyako"),
        Msg::DepartTapHint => o.write_str("idhinisha au kataa kwenye kifaa chako kingine chochote,\nau gusanisha kimoja wapo na hiki"),
        Msg::DepartThen => o.write_str("kikiidhinishwa, vitu vyako vinafutwa kutoka kwake\nna kinaanza upya; rudi huacha kuondoka"),
        Msg::DepartDeniedOn(name) => write!(o, "kuondoka kumekataliwa kwenye {name}"),
        Msg::DepartNotStarted => o.write_str("kuondoka hakukuanza"),
        Msg::LastDevice => o.write_str("Hiki ndicho kifaa cha mwisho cha utambulisho wako.\nHakiwezi kuondoka. Ongeza kifaa kingine kwanza, kisha ukistaafishe hiki."),
    }
}
