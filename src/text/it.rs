// Italian: the translation of en.rs, the reference.
// Photon's arms are Photon's own Italian (photon 9a93f16c, src/ui/lang/it.rs); where Photon falls back to English (SelectedDevice, SelectedBy and the four fgtw.org lines) the Italian is written here in Photon's vocabulary. ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Aggiungi un dispositivo"),
        Msg::TapNearby => o.write_str("oppure tocca il dispositivo vicino che chiede di entrare:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} qui vicino"),
        Msg::TypeWords => o.write_str("Scrivi le parole che vedi sul nuovo dispositivo"),
        Msg::InvalidWord(w) => write!(o, "'{w}' non è una delle parole"),
        Msg::WaitingForDevice => o.write_str("Aspetto il nuovo dispositivo\u{2026} dovrebbe star mostrando le sue parole"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} dispositivi chiedono di entrare: scrivi le parole di quello che hai in mano"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' non corrisponde a nessun dispositivo che chieda di entrare"),
        Msg::MatchingDevice(name) => write!(o, "confronto con {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "confronto\u{2026} ({shown} dispositivi)"),
        Msg::Preparing => o.write_str("Preparazione\u{2026}"),
        Msg::NoFleetKey => o.write_str("Questo dispositivo non ha ancora la chiave della flotta.\nFallo da un altro dei tuoi dispositivi."),
        Msg::NoDeviceKey => o.write_str("La chiave di questo dispositivo non è ancora pronta. Riprova tra un momento."),
        Msg::AddingDevice(name) => write!(o, "Aggiunta di {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Dispositivo aggiunto \u{221a}"),
        Msg::JoinContended => o.write_str("Più di un dispositivo chiede di entrare, quindi ora si può aggiungere solo un dispositivo accanto a questo, via Bluetooth o NFC. Se ne stai aggiungendo solo uno, qualcun altro conosce il tuo handle."),
        Msg::AddFromSignedIn => o.write_str("Aggiungi questo dispositivo da uno che è già tuo:"),
        Msg::AddDevicePill => o.write_str("Aggiungi dispositivo"),
        Msg::SelectedDevice(name) => write!(o, "Selezionato: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Il tuo nuovo dispositivo è verde brillante?"),
        Msg::YesPill => o.write_str("Sì"),
        Msg::NoPill => o.write_str("No"),
        Msg::AddLookFgtw => o.write_str("Non è qui vicino? Cerca tramite fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Cerco anche tramite fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("un dispositivo su questa rete chiede di entrare"),
        Msg::AddAsking => o.write_str("aggiungi dispositivo: dispositivi che chiedono di entrare"),
        Msg::AddSelected => o.write_str("aggiungi dispositivo: selezionato"),
        Msg::AddingToFleet => o.write_str("aggiunta alla flotta in corso"),
        Msg::HandingKey => o.write_str("consegna della chiave della flotta"),
        Msg::Added => o.write_str("aggiunto"),
        Msg::AddingFailed => o.write_str("aggiunta non riuscita"),
        Msg::CandAdded(name) => write!(o, "{name}  aggiunto"),
        Msg::CandNearby(name) => write!(o, "{name}  vicino: tocca per selezionarlo"),
        Msg::CandNotNearby(name) => write!(o, "{name}  lontano: scrivi le sue parole"),
        Msg::OpenPhotonJoin => o.write_str("apri la schermata di ingresso di Photon sul dispositivo"),
        Msg::TypeItsWordsPill => o.write_str("scrivi le sue parole"),
        Msg::HoldTogether => o.write_str("oppure avvicina i due dispositivi: entra subito"),
        Msg::DonePill => o.write_str("fatto"),
        Msg::ClosePill => o.write_str("chiudi"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Selezionato da {name}"),
        Msg::JoinerSelected => o.write_str("Scelto!"),
        Msg::JoinerConfirmOther => o.write_str("Conferma sull’altro dispositivo per finire."),
        Msg::LaunchJoinConfirmNote => o.write_str("L’aggiunta la confermi su quel dispositivo."),
        Msg::JoinAskFgtw => o.write_str("I miei dispositivi non sono qui vicino: chiedi tramite fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Richiesta inviata tramite fgtw.org: scrivi le parole sull’altro dispositivo"),
        Msg::HandlesDontMatch => o.write_str("i due non corrispondono\ncorreggi il nome e riprova"),
        Msg::DeviceBrandedHint => o.write_str("Questo hardware è ancora registrato a un’altra flotta.\nChi lo possiede può liberarlo con Libera dalla sua pagina Flotta."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Usa un dispositivo che hai già per legare questo alla tua flotta."),
        Msg::WaitingFleetKeys => o.write_str("In attesa delle chiavi della flotta."),
        Msg::BoundWaitingKeys => o.write_str("Legato alla tua flotta.\nIn attesa delle sue chiavi."),
        Msg::DeniedBoundOther => o.write_str("Rifiutato. Questo dispositivo è legato a un’altra identità."),
        Msg::OwnedByOther => o.write_str("Questo dispositivo appartiene a un’altra identità.\nSolo la sua flotta può lasciarlo andare."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("questo dispositivo"),
        Msg::ADevice => o.write_str("un dispositivo"),
        Msg::TheDevice => o.write_str("il dispositivo"),
        Msg::OneOfYourDevices => o.write_str("uno dei tuoi dispositivi"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  questo dispositivo"),
        Msg::MemberNearby(name) => write!(o, "{name}  vicino"),
        Msg::NoIdentityHere => o.write_str("nessuna identità qui"),
        Msg::JoiningConfirm => o.write_str("ingresso: conferma su uno dei tuoi dispositivi"),
        Msg::InFleetWaitingKey => o.write_str("nella flotta, in attesa della sua chiave"),
        Msg::InFleet => o.write_str("nella flotta"),
        Msg::LeavingFleet => o.write_str("uscita dalla flotta"),
        Msg::NewIdentityNoFleet => o.write_str("un’identità nuova: nessuna flotta la contiene ancora"),
        Msg::HandleHasOtherFleet => o.write_str("questo handle ha la flotta di un’altra identità"),
        Msg::NoVerdict => o.write_str("nessun verdetto: non risponde niente"),
        Msg::LookingUp => o.write_str("ricerca dell’identità"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} chiede di lasciare la tua flotta. Approvalo in Impostazioni → Flotta."),
        Msg::DepartRequestLine(name) => write!(o, "{name} chiede di lasciare la tua flotta."),
        Msg::DepartFreesHardware => o.write_str("Approvare lo cancella e libera il suo hardware, che potrà entrare in qualsiasi flotta."),
        Msg::DepartKeepsHardware => o.write_str("Approvare lo cancella.\nIl suo hardware resta registrato alla tua flotta."),
        Msg::DepartApprovePill => o.write_str("Approva"),
        Msg::DepartDenyPill => o.write_str("Rifiuta"),
        Msg::DepartDeniedHere(name) => write!(o, "Rifiutato. {name} resta nella tua flotta."),
        Msg::DepartComplete(n) => write!(o, "{n} ha lasciato la tua flotta.\nIl suo hardware è libero."),
        Msg::FleetSignedOut(name) => write!(o, "{name} ha lasciato la flotta."),
        Msg::DepartReleasePending(n) => write!(o, "{n} ha lasciato la tua flotta, ma il suo hardware non è stato liberato.\nUsa Libera sulla sua riga di dispositivo ritirato per riprovare."),
        Msg::DeviceReleased(name) => write!(o, "{name} è libero.\nOra può entrare in qualsiasi flotta."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("rifiutare lo tiene nella tua flotta"),
        Msg::DepartApproveAgainPill => o.write_str("approva di nuovo: l’ultima non è partita"),
        Msg::DepartApproving => o.write_str("approvazione in corso"),
        Msg::DepartApproved => o.write_str("approvato: sta lasciando la tua flotta"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Sto chiedendo agli altri tuoi dispositivi di lasciar andare questo. Approva su uno qualsiasi."),
        Msg::DepartDenied => o.write_str("Uno dei tuoi dispositivi ha rifiutato questa richiesta, quindi questo dispositivo resta nella tua flotta. Premi Libera per chiedere di nuovo."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "tocca di nuovo: rimuovi questo dispositivo" } else { "rimuovi questo dispositivo" }),
        Msg::DepartAsking => o.write_str("questo dispositivo chiede alla tua flotta di essere liberato"),
        Msg::DepartSending => o.write_str("invio della richiesta ai tuoi dispositivi"),
        Msg::DepartTapHint => o.write_str("approva o rifiuta su uno qualsiasi dei tuoi altri dispositivi,\no avvicinane uno a questo"),
        Msg::DepartThen => o.write_str("una volta approvato, le tue cose vengono cancellate dal dispositivo\ne si riavvia; indietro rinuncia all’uscita"),
        Msg::DepartDeniedOn(name) => write!(o, "l’uscita è stata rifiutata su {name}"),
        Msg::DepartNotStarted => o.write_str("l’uscita non è partita"),
        Msg::LastDevice => o.write_str("Questo è l’ultimo dispositivo della tua identità.\nNon può uscire. Aggiungi prima un altro dispositivo, poi ritira questo."),
    }
}
