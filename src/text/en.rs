// English: the reference; every other language is an exhaustive match over the same messages.
// Photon's messages in Photon's words (photon 9a93f16c, src/ui/lang/en.rs); ferros's in ferros's lower-case voice.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Add a device"),
        Msg::TapNearby => o.write_str("or tap the nearby device asking to join:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} nearby"),
        Msg::TypeWords => o.write_str("Type the words shown on the new device"),
        Msg::InvalidWord(w) => write!(o, "'{w}' isn't one of the words"),
        Msg::WaitingForDevice => o.write_str("Waiting for the new device\u{2026} it should be showing its words"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} devices asking to join: type the words on the one in your hand"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' doesn't match any device asking to join"),
        Msg::MatchingDevice(name) => write!(o, "matching {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "matching\u{2026} ({shown} devices)"),
        Msg::Preparing => o.write_str("Preparing\u{2026}"),
        Msg::NoFleetKey => o.write_str("This device doesn't hold the fleet key yet.\nDo this from another of your devices."),
        Msg::NoDeviceKey => o.write_str("This device's key isn't ready yet. Try again in a moment."),
        Msg::AddingDevice(name) => write!(o, "Adding {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Device added \u{221a}"),
        Msg::JoinContended => o.write_str("More than one device is asking to join, so only a device beside this one can be added now, by Bluetooth or NFC. If you are adding just one, someone else knows your handle."),
        Msg::AddFromSignedIn => o.write_str("Add this device from one that's already yours:"),
        Msg::AddDevicePill => o.write_str("Add device"),
        Msg::SelectedDevice(name) => write!(o, "Selected: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Is your new device bright green?"),
        Msg::YesPill => o.write_str("Yes"),
        Msg::NoPill => o.write_str("No"),
        Msg::AddLookFgtw => o.write_str("Not nearby? Look through fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Looking through fgtw.org too"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("a device on this network is asking to join"),
        Msg::AddAsking => o.write_str("add a device: devices asking to join"),
        Msg::AddSelected => o.write_str("add a device: selected"),
        Msg::AddingToFleet => o.write_str("adding it to the fleet"),
        Msg::HandingKey => o.write_str("handing it the fleet's key"),
        Msg::Added => o.write_str("added"),
        Msg::AddingFailed => o.write_str("adding it failed"),
        Msg::CandAdded(name) => write!(o, "{name}  added"),
        Msg::CandNearby(name) => write!(o, "{name}  nearby: tap to select"),
        Msg::CandNotNearby(name) => write!(o, "{name}  not nearby: type its words"),
        Msg::OpenPhotonJoin => o.write_str("open Photon's join screen on the device"),
        Msg::TypeItsWordsPill => o.write_str("type its words"),
        Msg::HoldTogether => o.write_str("or hold the two devices together: it joins at once"),
        Msg::DonePill => o.write_str("done"),
        Msg::ClosePill => o.write_str("close"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Selected by {name}"),
        Msg::JoinerSelected => o.write_str("Selected!"),
        Msg::JoinerConfirmOther => o.write_str("Confirm on your other device to finish."),
        Msg::LaunchJoinConfirmNote => o.write_str("You'll confirm the add on that device."),
        Msg::JoinAskFgtw => o.write_str("My devices aren't nearby: ask through fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Asked through fgtw.org: type the words on your other device"),
        Msg::HandlesDontMatch => o.write_str("the two don't match\nfix the name and try again"),
        Msg::DeviceBrandedHint => o.write_str("This hardware is still registered to another fleet.\nIts owner can free it with Release on their Fleet page."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Use an existing device to bind this device to your fleet."),
        Msg::WaitingFleetKeys => o.write_str("Waiting for the fleet's keys."),
        Msg::BoundWaitingKeys => o.write_str("Bound to your fleet.\nWaiting for its keys."),
        Msg::DeniedBoundOther => o.write_str("Denied. This device is bound to another identity."),
        Msg::OwnedByOther => o.write_str("This device belongs to another identity.\nOnly its fleet can let it go."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("this device"),
        Msg::ADevice => o.write_str("a device"),
        Msg::TheDevice => o.write_str("the device"),
        Msg::OneOfYourDevices => o.write_str("one of your devices"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  this device"),
        Msg::MemberNearby(name) => write!(o, "{name}  nearby"),
        Msg::NoIdentityHere => o.write_str("no identity here"),
        Msg::JoiningConfirm => o.write_str("joining: confirm on one of your devices"),
        Msg::InFleetWaitingKey => o.write_str("in the fleet, waiting for its key"),
        Msg::InFleet => o.write_str("in the fleet"),
        Msg::LeavingFleet => o.write_str("leaving the fleet"),
        Msg::NewIdentityNoFleet => o.write_str("a new identity: no fleet holds it yet"),
        Msg::HandleHasOtherFleet => o.write_str("this handle has another identity's fleet"),
        Msg::NoVerdict => o.write_str("no verdict: nothing answers"),
        Msg::LookingUp => o.write_str("looking the identity up"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} asks to leave your fleet. Approve it in Settings \u{2192} Fleet."),
        Msg::DepartRequestLine(name) => write!(o, "{name} asks to leave your fleet."),
        Msg::DepartFreesHardware => o.write_str("Approving wipes it and frees its hardware to join any fleet."),
        Msg::DepartKeepsHardware => o.write_str("Approving wipes it.\nIts hardware stays registered to your fleet."),
        Msg::DepartApprovePill => o.write_str("Approve"),
        Msg::DepartDenyPill => o.write_str("Deny"),
        Msg::DepartDeniedHere(name) => write!(o, "Denied. {name} stays in your fleet."),
        Msg::DepartComplete(n) => write!(o, "{n} has left your fleet.\nIts hardware is free."),
        Msg::FleetSignedOut(name) => write!(o, "{name} left the fleet."),
        Msg::DepartReleasePending(n) => write!(o, "{n} has left your fleet, but its hardware wasn't freed.\nPress Release on its retired row to try again."),
        Msg::DeviceReleased(name) => write!(o, "{name} is released.\nIt can join any fleet now."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("denying keeps it in your fleet"),
        Msg::DepartApproveAgainPill => o.write_str("approve again: the last one did not go out"),
        Msg::DepartApproving => o.write_str("approving"),
        Msg::DepartApproved => o.write_str("approved: it is leaving your fleet"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Asking your other devices to let this one leave. Approve on any of them."),
        Msg::DepartDenied => o.write_str("One of your devices denied this request, so this device stays in your fleet. Press Release to ask again."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "tap again: remove this device" } else { "remove this device" }),
        Msg::DepartAsking => o.write_str("this device is asking your fleet for its release"),
        Msg::DepartSending => o.write_str("sending the request to your devices"),
        Msg::DepartTapHint => o.write_str("approve or deny on any of your other devices,\nor tap one of them to this one"),
        Msg::DepartThen => o.write_str("once approved, your things are wiped from it\nand it restarts; back gives up leaving"),
        Msg::DepartDeniedOn(name) => write!(o, "leaving was denied on {name}"),
        Msg::DepartNotStarted => o.write_str("the departure did not start"),
        Msg::LastDevice => o.write_str("This is your identity's last device.\nIt can't leave. Add another device first, then retire this one."),
    }
}
