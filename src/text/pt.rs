// Portuguese: the translation of en.rs, the reference.
// Photon's arms are Photon's own Portuguese (photon 9a93f16c, src/ui/lang/pt.rs); where Photon falls back to English (SelectedDevice, SelectedBy and the four fgtw.org lines) the Portuguese is written here in Photon's vocabulary. ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Adicionar um dispositivo"),
        Msg::TapNearby => o.write_str("ou toque no dispositivo por perto que pede para entrar:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} por perto"),
        Msg::TypeWords => o.write_str("Digite as palavras que aparecem no novo dispositivo"),
        Msg::InvalidWord(w) => write!(o, "'{w}' não é uma das palavras"),
        Msg::WaitingForDevice => o.write_str("Esperando o novo dispositivo\u{2026} ele deve estar mostrando as palavras dele"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} dispositivos pedem para entrar: digite as palavras do que está na sua mão"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' não bate com nenhum dispositivo pedindo para entrar"),
        Msg::MatchingDevice(name) => write!(o, "conferindo {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "conferindo\u{2026} ({shown} dispositivos)"),
        Msg::Preparing => o.write_str("Preparando\u{2026}"),
        Msg::NoFleetKey => o.write_str("Este dispositivo ainda não tem a chave da frota.\nFaça isso de outro dos seus dispositivos."),
        Msg::NoDeviceKey => o.write_str("A chave deste dispositivo ainda não está pronta. Tente de novo daqui a pouco."),
        Msg::AddingDevice(name) => write!(o, "Adicionando {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Dispositivo adicionado \u{221a}"),
        Msg::JoinContended => o.write_str("Mais de um dispositivo pede para entrar, então agora só dá para adicionar um que esteja ao lado deste, por Bluetooth ou NFC. Se você está adicionando só um, outra pessoa conhece seu handle."),
        Msg::AddFromSignedIn => o.write_str("Adicione este dispositivo a partir de um que já é seu:"),
        Msg::AddDevicePill => o.write_str("Adicionar dispositivo"),
        Msg::SelectedDevice(name) => write!(o, "Selecionado: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Seu novo dispositivo está verde brilhante?"),
        Msg::YesPill => o.write_str("Sim"),
        Msg::NoPill => o.write_str("Não"),
        Msg::AddLookFgtw => o.write_str("Não está por perto? Procure pelo fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Procurando também pelo fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("um dispositivo nesta rede está pedindo para entrar"),
        Msg::AddAsking => o.write_str("adicionar dispositivo: dispositivos pedindo para entrar"),
        Msg::AddSelected => o.write_str("adicionar dispositivo: selecionado"),
        Msg::AddingToFleet => o.write_str("adicionando à frota"),
        Msg::HandingKey => o.write_str("entregando a chave da frota"),
        Msg::Added => o.write_str("adicionado"),
        Msg::AddingFailed => o.write_str("falha ao adicionar"),
        Msg::CandAdded(name) => write!(o, "{name}  adicionado"),
        Msg::CandNearby(name) => write!(o, "{name}  por perto: toque para selecionar"),
        Msg::CandNotNearby(name) => write!(o, "{name}  longe: digite as palavras dele"),
        Msg::OpenPhotonJoin => o.write_str("abra a tela de entrar do Photon no dispositivo"),
        Msg::TypeItsWordsPill => o.write_str("digitar as palavras dele"),
        Msg::HoldTogether => o.write_str("ou encoste os dois dispositivos: ele entra na hora"),
        Msg::DonePill => o.write_str("pronto"),
        Msg::ClosePill => o.write_str("fechar"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Selecionado por {name}"),
        Msg::JoinerSelected => o.write_str("Selecionado!"),
        Msg::JoinerConfirmOther => o.write_str("Confirme no seu outro dispositivo para terminar."),
        Msg::LaunchJoinConfirmNote => o.write_str("Você confirma a adição naquele dispositivo."),
        Msg::JoinAskFgtw => o.write_str("Meus dispositivos não estão por perto: pedir pelo fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Pedido feito pelo fgtw.org: digite as palavras no seu outro dispositivo"),
        Msg::HandlesDontMatch => o.write_str("os dois não batem\ncorrija o nome e tente de novo"),
        Msg::DeviceBrandedHint => o.write_str("Este hardware ainda está registrado em outra frota.\nQuem é dono dela pode liberá-lo com Liberar na página de Frota."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Use um dispositivo que você já tem para vincular este à sua frota."),
        Msg::WaitingFleetKeys => o.write_str("Esperando as chaves da frota."),
        Msg::BoundWaitingKeys => o.write_str("Vinculado à sua frota.\nEsperando as chaves dela."),
        Msg::DeniedBoundOther => o.write_str("Recusado. Este dispositivo está vinculado a outra identidade."),
        Msg::OwnedByOther => o.write_str("Este dispositivo pertence a outra identidade.\nSó a frota dela pode liberá-lo."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("este dispositivo"),
        Msg::ADevice => o.write_str("um dispositivo"),
        Msg::TheDevice => o.write_str("o dispositivo"),
        Msg::OneOfYourDevices => o.write_str("um dos seus dispositivos"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  este dispositivo"),
        Msg::MemberNearby(name) => write!(o, "{name}  por perto"),
        Msg::NoIdentityHere => o.write_str("nenhuma identidade aqui"),
        Msg::JoiningConfirm => o.write_str("entrando: confirme em um dos seus dispositivos"),
        Msg::InFleetWaitingKey => o.write_str("na frota, esperando a chave dela"),
        Msg::InFleet => o.write_str("na frota"),
        Msg::LeavingFleet => o.write_str("saindo da frota"),
        Msg::NewIdentityNoFleet => o.write_str("uma identidade nova: nenhuma frota a tem ainda"),
        Msg::HandleHasOtherFleet => o.write_str("este handle tem a frota de outra identidade"),
        Msg::NoVerdict => o.write_str("sem veredito: nada responde"),
        Msg::LookingUp => o.write_str("procurando a identidade"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} pede para sair da sua frota. Aprove em Ajustes → Frota."),
        Msg::DepartRequestLine(name) => write!(o, "{name} pede para sair da sua frota."),
        Msg::DepartFreesHardware => o.write_str("Aprovar apaga o dispositivo e libera o hardware dele para entrar em qualquer frota."),
        Msg::DepartKeepsHardware => o.write_str("Aprovar apaga o dispositivo.\nO hardware dele continua registrado na sua frota."),
        Msg::DepartApprovePill => o.write_str("Aprovar"),
        Msg::DepartDenyPill => o.write_str("Recusar"),
        Msg::DepartDeniedHere(name) => write!(o, "Recusado. {name} continua na sua frota."),
        Msg::DepartComplete(n) => write!(o, "{n} saiu da sua frota.\nO hardware dele está livre."),
        Msg::FleetSignedOut(name) => write!(o, "{name} saiu da frota."),
        Msg::DepartReleasePending(n) => write!(o, "{n} saiu da sua frota, mas o hardware dele não foi liberado.\nToque em Liberar na linha aposentada dele para tentar de novo."),
        Msg::DeviceReleased(name) => write!(o, "{name} está liberado.\nAgora pode entrar em qualquer frota."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("recusar o mantém na sua frota"),
        Msg::DepartApproveAgainPill => o.write_str("aprovar de novo: a última não saiu"),
        Msg::DepartApproving => o.write_str("aprovando"),
        Msg::DepartApproved => o.write_str("aprovado: está saindo da sua frota"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Pedindo aos seus outros dispositivos que deixem este sair. Aprove em qualquer um deles."),
        Msg::DepartDenied => o.write_str("Um dos seus dispositivos recusou este pedido, então este dispositivo continua na sua frota. Toque em Liberar para pedir de novo."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "toque de novo: remover este dispositivo" } else { "remover este dispositivo" }),
        Msg::DepartAsking => o.write_str("este dispositivo está pedindo à sua frota que o libere"),
        Msg::DepartSending => o.write_str("enviando o pedido aos seus dispositivos"),
        Msg::DepartTapHint => o.write_str("aprove ou recuse em qualquer um dos seus outros dispositivos,\nou encoste um deles neste"),
        Msg::DepartThen => o.write_str("depois de aprovado, as suas coisas são apagadas dele\ne ele reinicia; voltar desiste de sair"),
        Msg::DepartDeniedOn(name) => write!(o, "a saída foi recusada em {name}"),
        Msg::DepartNotStarted => o.write_str("a saída não começou"),
    }
}
