// Indonesian: an exhaustive match over the same messages as en.rs (the reference).
// Photon's arms are Photon's Indonesian (photon 9a93f16c, src/ui/lang/id.rs); ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
// Photon's id.rs falls back to English for SelectedDevice, SelectedBy, JoinAskFgtw, JoinAskedFgtw, AddLookFgtw and AddLookingFgtw, so those six are translated here from Photon's English.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Tambah sebuah perangkat"),
        Msg::TapNearby => o.write_str("atau ketuk perangkat di dekatmu yang minta bergabung:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} di dekat sini"),
        Msg::TypeWords => o.write_str("Ketik kata-kata yang ditampilkan perangkat baru itu"),
        Msg::InvalidWord(w) => write!(o, "'{w}' bukan salah satu katanya"),
        Msg::WaitingForDevice => o.write_str("Menunggu perangkat baru\u{2026} seharusnya ia sedang menampilkan kata-katanya"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} perangkat minta bergabung: ketik kata-kata dari yang ada di tanganmu"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' tidak cocok dengan perangkat mana pun yang minta bergabung"),
        Msg::MatchingDevice(name) => write!(o, "mencocokkan {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "mencocokkan\u{2026} ({shown} perangkat)"),
        Msg::Preparing => o.write_str("Menyiapkan\u{2026}"),
        Msg::NoFleetKey => o.write_str("Perangkat ini belum memegang kunci armada.\nLakukan dari perangkatmu yang lain."),
        Msg::NoDeviceKey => o.write_str("Kunci perangkat ini belum siap. Coba lagi sebentar."),
        Msg::AddingDevice(name) => write!(o, "Menambahkan {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Perangkat ditambahkan \u{221a}"),
        Msg::JoinContended => o.write_str("Lebih dari satu perangkat minta bergabung, jadi sekarang hanya perangkat di sebelah perangkat ini yang bisa ditambahkan, lewat Bluetooth atau NFC. Kalau kamu hanya menambah satu, orang lain tahu handle-mu."),
        Msg::AddFromSignedIn => o.write_str("Tambahkan perangkat ini dari perangkat yang sudah jadi milikmu:"),
        Msg::AddDevicePill => o.write_str("Tambah perangkat"),
        Msg::SelectedDevice(name) => write!(o, "Terpilih: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Apakah perangkat barumu hijau terang?"),
        Msg::YesPill => o.write_str("Ya"),
        Msg::NoPill => o.write_str("Tidak"),
        Msg::AddLookFgtw => o.write_str("Tidak di dekat sini? Cari lewat fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Juga mencari lewat fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("sebuah perangkat di jaringan ini minta bergabung"),
        Msg::AddAsking => o.write_str("tambah perangkat: perangkat yang minta bergabung"),
        Msg::AddSelected => o.write_str("tambah perangkat: terpilih"),
        Msg::AddingToFleet => o.write_str("menambahkannya ke armada"),
        Msg::HandingKey => o.write_str("menyerahkan kunci armada kepadanya"),
        Msg::Added => o.write_str("ditambahkan"),
        Msg::AddingFailed => o.write_str("gagal menambahkannya"),
        Msg::CandAdded(name) => write!(o, "{name}  ditambahkan"),
        Msg::CandNearby(name) => write!(o, "{name}  di dekat sini: ketuk untuk memilih"),
        Msg::CandNotNearby(name) => write!(o, "{name}  tidak di dekat sini: ketik kata-katanya"),
        Msg::OpenPhotonJoin => o.write_str("buka layar gabung Photon di perangkat itu"),
        Msg::TypeItsWordsPill => o.write_str("ketik kata-katanya"),
        Msg::HoldTogether => o.write_str("atau dekatkan kedua perangkat: ia langsung bergabung"),
        Msg::DonePill => o.write_str("selesai"),
        Msg::ClosePill => o.write_str("tutup"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Dipilih oleh {name}"),
        Msg::JoinerSelected => o.write_str("Terpilih!"),
        Msg::JoinerConfirmOther => o.write_str("Konfirmasi di perangkatmu yang lain untuk menyelesaikannya."),
        Msg::LaunchJoinConfirmNote => o.write_str("Kamu akan mengonfirmasi penambahannya di perangkat itu."),
        Msg::JoinAskFgtw => o.write_str("Perangkatku tidak di dekat sini: minta lewat fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Sudah diminta lewat fgtw.org: ketik kata-katanya di perangkatmu yang lain"),
        Msg::HandlesDontMatch => o.write_str("keduanya tidak cocok\nperbaiki namanya dan coba lagi"),
        Msg::DeviceBrandedHint => o.write_str("Perangkat keras ini masih terdaftar di armada lain.\nPemiliknya bisa membebaskannya dengan Lepas di halaman Armada miliknya."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Gunakan perangkat yang sudah kamu punya untuk mengikat perangkat ini ke armadamu."),
        Msg::WaitingFleetKeys => o.write_str("Menunggu kunci-kunci armada."),
        Msg::BoundWaitingKeys => o.write_str("Terikat ke armadamu.\nMenunggu kunci-kuncinya."),
        Msg::DeniedBoundOther => o.write_str("Ditolak. Perangkat ini terikat ke identitas lain."),
        Msg::OwnedByOther => o.write_str("Perangkat ini milik identitas lain.\nHanya armadanya yang bisa melepasnya."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("perangkat ini"),
        Msg::ADevice => o.write_str("sebuah perangkat"),
        Msg::TheDevice => o.write_str("perangkat itu"),
        Msg::OneOfYourDevices => o.write_str("salah satu perangkatmu"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  perangkat ini"),
        Msg::MemberNearby(name) => write!(o, "{name}  di dekat sini"),
        Msg::NoIdentityHere => o.write_str("tidak ada identitas di sini"),
        Msg::JoiningConfirm => o.write_str("bergabung: konfirmasi di salah satu perangkatmu"),
        Msg::InFleetWaitingKey => o.write_str("di armada, menunggu kuncinya"),
        Msg::InFleet => o.write_str("di armada"),
        Msg::LeavingFleet => o.write_str("keluar dari armada"),
        Msg::NewIdentityNoFleet => o.write_str("identitas baru: belum ada armada yang memegangnya"),
        Msg::HandleHasOtherFleet => o.write_str("handle ini punya armada identitas lain"),
        Msg::NoVerdict => o.write_str("tidak ada putusan: tidak ada yang menjawab"),
        Msg::LookingUp => o.write_str("mencari identitasnya"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} minta keluar dari armadamu. Setujui di Pengaturan → Armada."),
        Msg::DepartRequestLine(name) => write!(o, "{name} minta keluar dari armadamu."),
        Msg::DepartFreesHardware => o.write_str("Menyetujuinya akan menghapus perangkat itu dan membebaskan perangkat kerasnya untuk bergabung ke armada mana pun."),
        Msg::DepartKeepsHardware => o.write_str("Menyetujuinya akan menghapus perangkat itu.\nPerangkat kerasnya tetap terdaftar di armadamu."),
        Msg::DepartApprovePill => o.write_str("Setujui"),
        Msg::DepartDenyPill => o.write_str("Tolak"),
        Msg::DepartDeniedHere(name) => write!(o, "Ditolak. {name} tetap di armadamu."),
        Msg::DepartComplete(n) => write!(o, "{n} sudah keluar dari armadamu.\nPerangkat kerasnya sudah bebas."),
        Msg::FleetSignedOut(name) => write!(o, "{name} keluar dari armada."),
        Msg::DepartReleasePending(n) => write!(o, "{n} sudah keluar dari armadamu, tetapi perangkat kerasnya belum dibebaskan.\nTekan Lepas di barisnya yang pensiun untuk mencoba lagi."),
        Msg::DeviceReleased(name) => write!(o, "{name} sudah dilepas.\nSekarang ia bisa bergabung ke armada mana pun."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("menolaknya membuat perangkat itu tetap di armadamu"),
        Msg::DepartApproveAgainPill => o.write_str("setujui lagi: yang terakhir tidak terkirim"),
        Msg::DepartApproving => o.write_str("menyetujui"),
        Msg::DepartApproved => o.write_str("disetujui: ia sedang keluar dari armadamu"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Meminta perangkatmu yang lain agar mengizinkan perangkat ini keluar. Setujui di salah satunya."),
        Msg::DepartDenied => o.write_str("Salah satu perangkatmu menolak permintaan ini, jadi perangkat ini tetap di armadamu. Tekan Lepas untuk meminta lagi."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "ketuk lagi: keluarkan perangkat ini" } else { "keluarkan perangkat ini" }),
        Msg::DepartAsking => o.write_str("perangkat ini meminta armadamu melepasnya"),
        Msg::DepartSending => o.write_str("mengirim permintaan ke perangkat-perangkatmu"),
        Msg::DepartTapHint => o.write_str("setujui atau tolak di perangkatmu yang lain,\natau tempelkan salah satunya ke perangkat ini"),
        Msg::DepartThen => o.write_str("setelah disetujui, milikmu dihapus darinya\nlalu ia mulai ulang; kembali membatalkan keluar"),
        Msg::DepartDeniedOn(name) => write!(o, "permintaan keluar ditolak di {name}"),
        Msg::DepartNotStarted => o.write_str("kepergiannya tidak dimulai"),
        Msg::LastDevice => o.write_str("Ini perangkat terakhir identitasmu.\nIa tidak bisa keluar. Tambahkan perangkat lain dulu, lalu pensiunkan yang ini."),
    }
}
