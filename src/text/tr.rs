// Turkish: an exhaustive match over the same messages as en.rs (the reference).
// Photon's arms are Photon's words (photon 9a93f16c, src/ui/lang/tr.rs); SelectedDevice, SelectedBy, JoinAskFgtw, JoinAskedFgtw, AddLookFgtw and AddLookingFgtw, which Photon's tr.rs still shows in English, are translated here from Photon's English. ferros's arms are ferros's, in its lower-case voice, a best-effort translation pending native-speaker review, vocabulary following Photon's (filo, handle, kimlik, cihaz, kelimeler, onayla, reddet).
// As in Photon's tr.rs, no suffix is glued to an inserted name (its last vowel is unknown when this is compiled): each sentence keeps the name bare.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Bir cihaz ekle"),
        Msg::TapNearby => o.write_str("ya da katılmak isteyen yakındaki cihaza dokun:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} yakında"),
        Msg::TypeWords => o.write_str("Yeni cihazda görünen kelimeleri yaz"),
        Msg::InvalidWord(w) => write!(o, "'{w}' kelimelerden biri değil"),
        Msg::WaitingForDevice => o.write_str("Yeni cihaz bekleniyor\u{2026} kelimelerini gösteriyor olmalı"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} cihaz katılmak istiyor: elindekinin kelimelerini yaz"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' katılmak isteyen hiçbir cihazla eşleşmiyor"),
        Msg::MatchingDevice(name) => write!(o, "{name} eşleştiriliyor\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "eşleştiriliyor\u{2026} ({shown} cihaz)"),
        Msg::Preparing => o.write_str("Hazırlanıyor\u{2026}"),
        Msg::NoFleetKey => o.write_str("Bu cihazda henüz filo anahtarı yok.\nBunu başka bir cihazından yap."),
        Msg::NoDeviceKey => o.write_str("Bu cihazın anahtarı henüz hazır değil. Birazdan tekrar dene."),
        Msg::AddingDevice(name) => write!(o, "{name} ekleniyor\u{2026}"),
        Msg::DeviceAdded => o.write_str("Cihaz eklendi \u{221a}"),
        Msg::JoinContended => o.write_str("Birden fazla cihaz katılmak istiyor, bu yüzden şimdi yalnızca bunun yanındaki bir cihaz eklenebilir, Bluetooth ya da NFC ile. Yalnızca bir tane ekliyorsan, handle'ını başka biri biliyor."),
        Msg::AddFromSignedIn => o.write_str("Bu cihazı, zaten senin olan bir cihazdan ekle:"),
        Msg::AddDevicePill => o.write_str("Cihaz ekle"),
        Msg::SelectedDevice(name) => write!(o, "Seçildi: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Yeni cihazın parlak yeşil mi?"),
        Msg::YesPill => o.write_str("Evet"),
        Msg::NoPill => o.write_str("Hayır"),
        Msg::AddLookFgtw => o.write_str("Yakında değil mi? fgtw.org üzerinden ara"),
        Msg::AddLookingFgtw => o.write_str("fgtw.org üzerinden de aranıyor"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("bu ağdaki bir cihaz katılmak istiyor"),
        Msg::AddAsking => o.write_str("cihaz ekle: katılmak isteyen cihazlar"),
        Msg::AddSelected => o.write_str("cihaz ekle: seçildi"),
        Msg::AddingToFleet => o.write_str("filoya ekleniyor"),
        Msg::HandingKey => o.write_str("filonun anahtarı ona veriliyor"),
        Msg::Added => o.write_str("eklendi"),
        Msg::AddingFailed => o.write_str("eklenemedi"),
        Msg::CandAdded(name) => write!(o, "{name}  eklendi"),
        Msg::CandNearby(name) => write!(o, "{name}  yakında: seçmek için dokun"),
        Msg::CandNotNearby(name) => write!(o, "{name}  yakında değil: kelimelerini yaz"),
        Msg::OpenPhotonJoin => o.write_str("cihazda Photon'un katılma ekranını aç"),
        Msg::TypeItsWordsPill => o.write_str("kelimelerini yaz"),
        Msg::HoldTogether => o.write_str("ya da iki cihazı yan yana tut: hemen katılır"),
        Msg::DonePill => o.write_str("tamam"),
        Msg::ClosePill => o.write_str("kapat"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Seçen: {name}"),
        Msg::JoinerSelected => o.write_str("Seçildi!"),
        Msg::JoinerConfirmOther => o.write_str("Bitirmek için diğer cihazında onayla."),
        Msg::LaunchJoinConfirmNote => o.write_str("Eklemeyi o cihazda onaylayacaksın."),
        Msg::JoinAskFgtw => o.write_str("Cihazlarım yakında değil: fgtw.org üzerinden sor"),
        Msg::JoinAskedFgtw => o.write_str("fgtw.org üzerinden soruldu: kelimeleri diğer cihazında yaz"),
        Msg::HandlesDontMatch => o.write_str("ikisi eşleşmiyor\nadı düzelt ve tekrar dene"),
        Msg::DeviceBrandedHint => o.write_str("Bu donanım hâlâ başka bir filoya kayıtlı.\nSahibi onu kendi Filo sayfasındaki Serbest bırak ile serbest bırakabilir."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Bu cihazı filona bağlamak için mevcut bir cihazını kullan."),
        Msg::WaitingFleetKeys => o.write_str("Filonun anahtarları bekleniyor."),
        Msg::BoundWaitingKeys => o.write_str("Filona bağlandı.\nAnahtarları bekleniyor."),
        Msg::DeniedBoundOther => o.write_str("Reddedildi. Bu cihaz başka bir kimliğe bağlı."),
        Msg::OwnedByOther => o.write_str("Bu cihaz başka bir kimliğe ait.\nOnu yalnızca kendi filosu bırakabilir."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("bu cihaz"),
        Msg::ADevice => o.write_str("bir cihaz"),
        Msg::TheDevice => o.write_str("cihaz"),
        Msg::OneOfYourDevices => o.write_str("cihazlarından biri"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  bu cihaz"),
        Msg::MemberNearby(name) => write!(o, "{name}  yakında"),
        Msg::NoIdentityHere => o.write_str("burada kimlik yok"),
        Msg::JoiningConfirm => o.write_str("katılınıyor: cihazlarından birinde onayla"),
        Msg::InFleetWaitingKey => o.write_str("filoda, anahtarı bekleniyor"),
        Msg::InFleet => o.write_str("filoda"),
        Msg::LeavingFleet => o.write_str("filodan ayrılıyor"),
        Msg::NewIdentityNoFleet => o.write_str("yeni bir kimlik: henüz hiçbir filo onu tutmuyor"),
        Msg::HandleHasOtherFleet => o.write_str("bu handle başka bir kimliğin filosuna ait"),
        Msg::NoVerdict => o.write_str("karar yok: hiçbir şey yanıt vermiyor"),
        Msg::LookingUp => o.write_str("kimlik aranıyor"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} filondan ayrılmak istiyor. Ayarlar \u{2192} Filo sayfasında onayla."),
        Msg::DepartRequestLine(name) => write!(o, "{name} filondan ayrılmak istiyor."),
        Msg::DepartFreesHardware => o.write_str("Onaylamak onu siler ve donanımını herhangi bir filoya katılabilmesi için serbest bırakır."),
        Msg::DepartKeepsHardware => o.write_str("Onaylamak onu siler.\nDonanımı filona kayıtlı kalır."),
        Msg::DepartApprovePill => o.write_str("Onayla"),
        Msg::DepartDenyPill => o.write_str("Reddet"),
        Msg::DepartDeniedHere(name) => write!(o, "Reddedildi. {name} filonda kalıyor."),
        Msg::DepartComplete(n) => write!(o, "{n} filondan ayrıldı.\nDonanımı artık serbest."),
        Msg::FleetSignedOut(name) => write!(o, "{name} filodan ayrıldı."),
        Msg::DepartReleasePending(n) => write!(o, "{n} filondan ayrıldı ama donanımı serbest bırakılamadı.\nYeniden denemek için emekli satırındaki Serbest bırak düğmesine bas."),
        Msg::DeviceReleased(name) => write!(o, "{name} serbest bırakıldı.\nArtık herhangi bir filoya katılabilir."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("reddetmek onu filonda tutar"),
        Msg::DepartApproveAgainPill => o.write_str("tekrar onayla: sonuncusu gönderilemedi"),
        Msg::DepartApproving => o.write_str("onaylanıyor"),
        Msg::DepartApproved => o.write_str("onaylandı: filondan ayrılıyor"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Diğer cihazlarına bunun ayrılmasına izin verip vermeyecekleri soruluyor. Herhangi birinde onayla."),
        Msg::DepartDenied => o.write_str("Cihazlarından biri bu isteği reddetti, bu yüzden bu cihaz filonda kalıyor. Yeniden sormak için Serbest bırak düğmesine dokun."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "tekrar dokun: bu cihazı kaldır" } else { "bu cihazı kaldır" }),
        Msg::DepartAsking => o.write_str("bu cihaz filondan serbest bırakılmayı istiyor"),
        Msg::DepartSending => o.write_str("istek cihazlarına gönderiliyor"),
        Msg::DepartTapHint => o.write_str("diğer cihazlarından herhangi birinde onayla ya da reddet,\nya da birini bu cihaza dokundur"),
        Msg::DepartThen => o.write_str("onaylanınca senin olan her şey ondan silinir\nve yeniden başlar; geri, ayrılmaktan vazgeçer"),
        Msg::DepartDeniedOn(name) => write!(o, "ayrılma şu cihazda reddedildi: {name}"),
        Msg::DepartNotStarted => o.write_str("ayrılış başlamadı"),
    }
}
