// Photon's arms are Photon's own Māori (photon 9a93f16c, src/ui/lang/mi.rs); where Photon falls back to English (SelectedDevice, SelectedBy and the four fgtw.org lines) the Māori is written here in Photon's vocabulary (kāhui, tuakiri, pūrere, here, whakaae, whakakāhore, ngā kupu). ferros's arms are ferros's, in its lower-case voice.
