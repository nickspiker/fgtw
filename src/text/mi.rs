use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Tāpiri he pūrere"),
        Msg::TapNearby => o.write_str("pāwhiritia rānei te pūrere pātata e tono ana kia hono:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} pātata"),
        Msg::TypeWords => o.write_str("Tāurua ngā kupu e whakaaturia ana i te pūrere hou"),
        Msg::InvalidWord(w) => write!(o, "ehara a '{w}' i tētahi o ngā kupu"),
        Msg::WaitingForDevice => o.write_str("E tatari ana ki te pūrere hou\u{2026} me whakaatu ia i āna kupu"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} ngā pūrere e tono ana kia hono: tāurua ngā kupu o te mea kei tō ringa"),
        Msg::NoMatchingDevice(bad) => write!(o, "kāore a '{bad}' e hāngai ki tētahi pūrere e tono ana"),
        Msg::MatchingDevice(name) => write!(o, "e whakataurite ana i a {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "e whakataurite ana\u{2026} ({shown} ngā pūrere)"),
        Msg::Preparing => o.write_str("E whakarite ana\u{2026}"),
        Msg::NoFleetKey => o.write_str("Kāore anō te kī kāhui i tēnei pūrere.\nMahia mai i tētahi atu o ō pūrere."),
        Msg::NoDeviceKey => o.write_str("Kāore anō te kī o tēnei pūrere kia rite. Ngana anō ākuanei."),
        Msg::AddingDevice(name) => write!(o, "E tāpiri ana i a {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Kua tāpirihia te pūrere \u{221a}"),
        Msg::JoinContended => o.write_str("Neke atu i te kotahi ngā pūrere e tono ana kia hono, nā reira ko te pūrere anake kei te taha o tēnei ka tāpirihia ināianei, mā te Bluetooth, mā te NFC rānei. Mēnā kotahi anake tāu e tāpiri ana, e mōhio ana tētahi atu ki tō handle."),
        Msg::AddFromSignedIn => o.write_str("Tāpirihia tēnei pūrere mai i tētahi nōu kē:"),
        Msg::AddDevicePill => o.write_str("Tāpiri pūrere"),
        Msg::SelectedDevice(name) => write!(o, "Kua tīpakohia: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("Kei te k\u{0101}k\u{0101}riki kanapa t\u{014D} p\u{016B}rere hou?"),
        Msg::YesPill => o.write_str("\u{0100}e"),
        Msg::NoPill => o.write_str("K\u{0101}o"),
        Msg::AddLookFgtw => o.write_str("Kāore i te pātata? Rapua mā fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("E rapu ana mā fgtw.org hoki"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("e tono ana tētahi pūrere i tēnei whatunga kia hono"),
        Msg::AddAsking => o.write_str("tāpiri pūrere: ngā pūrere e tono ana kia hono"),
        Msg::AddSelected => o.write_str("tāpiri pūrere: kua tīpakohia"),
        Msg::AddingToFleet => o.write_str("e tāpiri ana i a ia ki te kāhui"),
        Msg::HandingKey => o.write_str("e hoatu ana i te kī o te kāhui ki a ia"),
        Msg::Added => o.write_str("kua tāpirihia"),
        Msg::AddingFailed => o.write_str("i rahua te tāpiri"),
        Msg::CandAdded(name) => write!(o, "{name}  kua tāpirihia"),
        Msg::CandNearby(name) => write!(o, "{name}  pātata: pāwhiritia hei tīpako"),
        Msg::CandNotNearby(name) => write!(o, "{name}  kāore i te pātata: tāurua āna kupu"),
        Msg::OpenPhotonJoin => o.write_str("whakatuwheratia te mata hono o Photon i te pūrere"),
        Msg::TypeItsWordsPill => o.write_str("tāurua āna kupu"),
        Msg::HoldTogether => o.write_str("pupuritia rānei ngā pūrere e rua kia piri: ka hono tonu ia"),
        Msg::DonePill => o.write_str("kua oti"),
        Msg::ClosePill => o.write_str("kati"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Kua tīpakohia e {name}"),
        Msg::JoinerSelected => o.write_str("Kua tīpakohia!"),
        Msg::JoinerConfirmOther => o.write_str("Whakaūngia i tō pūrere kē kia oti."),
        Msg::LaunchJoinConfirmNote => o.write_str("Māu te tāpiri e whakaū i taua pūrere."),
        Msg::JoinAskFgtw => o.write_str("Kāore ōku pūrere i te pātata: tonoa mā fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Kua tono mā fgtw.org: tāurua ngā kupu i tō pūrere kē"),
        Msg::HandlesDontMatch => o.write_str("kāore e ōrite ana ngā mea e rua\nwhakatikahia te ingoa ka ngana anō"),
        Msg::DeviceBrandedHint => o.write_str("Kei te r\u{0113}hita tonu t\u{0113}nei taputapu ki t\u{0113}tahi atu k\u{0101}hui.\nKa taea e t\u{014D}na rangatira te wewete, m\u{0101} te Tuku i t\u{014D} r\u{0101}tou wh\u{0101}rangi K\u{0101}hui."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Whakamahia tētahi pūrere kei a koe kē hei here i tēnei pūrere ki tō kāhui."),
        Msg::WaitingFleetKeys => o.write_str("E tatari ana ki ngā kī o te kāhui."),
        Msg::BoundWaitingKeys => o.write_str("Kua herea ki tō kāhui.\nE tatari ana ki ōna kī."),
        Msg::DeniedBoundOther => o.write_str("Kua whakakāhoretia. Kua herea tēnei pūrere ki tētahi atu tuakiri."),
        Msg::OwnedByOther => o.write_str("Nō tētahi atu tuakiri tēnei pūrere.\nMā tōna kāhui anake ia e tuku."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("tēnei pūrere"),
        Msg::ADevice => o.write_str("tētahi pūrere"),
        Msg::TheDevice => o.write_str("te pūrere"),
        Msg::OneOfYourDevices => o.write_str("tētahi o ō pūrere"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  tēnei pūrere"),
        Msg::MemberNearby(name) => write!(o, "{name}  pātata"),
        Msg::NoIdentityHere => o.write_str("kāore he tuakiri i konei"),
        Msg::JoiningConfirm => o.write_str("e hono ana: whakaūngia i tētahi o ō pūrere"),
        Msg::InFleetWaitingKey => o.write_str("kei te kāhui, e tatari ana ki tōna kī"),
        Msg::InFleet => o.write_str("kei te kāhui"),
        Msg::LeavingFleet => o.write_str("e wehe ana i te kāhui"),
        Msg::NewIdentityNoFleet => o.write_str("he tuakiri hou: kāore anō he kāhui e pupuri ana i a ia"),
        Msg::HandleHasOtherFleet => o.write_str("kei tēnei handle te kāhui o tētahi atu tuakiri"),
        Msg::NoVerdict => o.write_str("kāore he whakatau: kāore tētahi e whakautu ana"),
        Msg::LookingUp => o.write_str("e rapu ana i te tuakiri"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "e tono ana a {name} kia wehe i tō kāhui. Whakaaetia i Tautuhinga → Kāhui."),
        Msg::DepartRequestLine(name) => write!(o, "E tono ana a {name} kia wehe i tō kāhui."),
        Msg::DepartFreesHardware => o.write_str("M\u{0101} te whakaae ka \u{016B}kuia, ka wetekina hoki t\u{014D}na taputapu kia hono ki t\u{0113}tahi k\u{0101}hui, ahakoa ko t\u{0113}hea."),
        Msg::DepartKeepsHardware => o.write_str("M\u{0101} te whakaae ka \u{016B}kuia.\nKa noho r\u{0113}hita tonu t\u{014D}na taputapu ki t\u{014D} k\u{0101}hui."),
        Msg::DepartApprovePill => o.write_str("Whakaae"),
        Msg::DepartDenyPill => o.write_str("Whakakāhore"),
        Msg::DepartDeniedHere(name) => write!(o, "Kua whakakāhoretia. Ka noho tonu a {name} ki tō kāhui."),
        Msg::DepartComplete(n) => write!(o, "Kua wehe a {n} i t\u{014D} k\u{0101}hui.\nKua w\u{0101}tea t\u{014D}na taputapu."),
        Msg::FleetSignedOut(name) => write!(o, "kua wehe a {name} i te kāhui."),
        Msg::DepartReleasePending(n) => write!(o, "Kua wehe a {n} i t\u{014D} k\u{0101}hui, engari k\u{0101}ore t\u{014D}na taputapu i wetekina.\nP\u{0101}whiritia te Tuku i t\u{014D}na r\u{0101}rangi kua whakat\u{0101} hei ng\u{0101}na an\u{014D}."),
        Msg::DeviceReleased(name) => write!(o, "Kua tukuna a {name}.\nKa taea e ia te hono ki tētahi kāhui ināianei, ahakoa ko tēhea."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("mā te whakakāhore ka noho tonu ia ki tō kāhui"),
        Msg::DepartApproveAgainPill => o.write_str("whakaae anō: kāore te mea whakamutunga i puta"),
        Msg::DepartApproving => o.write_str("e whakaae ana"),
        Msg::DepartApproved => o.write_str("kua whakaaetia: e wehe ana ia i tō kāhui"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("E tono ana ki ō pūrere kē kia tukua tēnei kia wehe. Whakaaetia i tētahi o rātou."),
        Msg::DepartDenied => o.write_str("I whakakāhoretia tēnei tono e tētahi o ō pūrere, nō reira ka noho tonu tēnei pūrere ki tō kāhui. Pēhia a Tuku kia tono anō."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "pāwhiri anō: tangohia tēnei pūrere" } else { "tangohia tēnei pūrere" }),
        Msg::DepartAsking => o.write_str("e tono ana tēnei pūrere ki tō kāhui kia tukua ia"),
        Msg::DepartSending => o.write_str("e tuku ana i te tono ki ō pūrere"),
        Msg::DepartTapHint => o.write_str("whakaaetia, whakakāhoretia rānei i tētahi atu o ō pūrere,\nwhakapāngia rānei tētahi o ērā ki tēnei"),
        Msg::DepartThen => o.write_str("ina whakaaetia, ka ūkuia ō mea i runga i a ia\nkātahi ka tīmata anō; mā hoki e whakamutu te wehe"),
        Msg::DepartDeniedOn(name) => write!(o, "i whakakāhoretia te wehe i {name}"),
        Msg::DepartNotStarted => o.write_str("kāore te wehenga i tīmata"),
        Msg::LastDevice => o.write_str("Ko te pūrere whakamutunga tēnei o tō tuakiri.\nKāore e taea te wehe. Tāpirihia he pūrere kē i te tuatahi, kātahi ka whakatā i tēnei."),
    }
}
