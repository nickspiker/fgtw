// Spanish: the translation of en.rs, the reference.
// Photon's arms are Photon's own Spanish (photon 9a93f16c, src/ui/lang/es.rs); where Photon falls back to English (SelectedDevice, SelectedBy and the four fgtw.org lines) the Spanish is written here in Photon's vocabulary. ferros's arms are ferros's, in its lower-case voice, pending a native speaker's review.
use super::Msg;
use core::fmt::{self, Write};

pub fn text(m: Msg, o: &mut dyn Write) -> fmt::Result {
    match m {
        // ---- Photon's: adding a device ----
        Msg::AddDeviceTitle => o.write_str("Agregar un dispositivo"),
        Msg::TapNearby => o.write_str("o toca el dispositivo cercano que pide unirse:"),
        Msg::AddDeviceNearby(name) => write!(o, "{name}   \u{00b7} cerca"),
        Msg::TypeWords => o.write_str("Escribe las palabras que muestra el nuevo dispositivo"),
        Msg::InvalidWord(w) => write!(o, "'{w}' no es una de las palabras"),
        Msg::WaitingForDevice => o.write_str("Esperando al nuevo dispositivo\u{2026} debería estar mostrando sus palabras"),
        Msg::DevicesAskingToJoin { shown, .. } => write!(o, "{shown} dispositivos piden unirse: escribe las palabras del que tienes en la mano"),
        Msg::NoMatchingDevice(bad) => write!(o, "'{bad}' no coincide con ningún dispositivo que pida unirse"),
        Msg::MatchingDevice(name) => write!(o, "comprobando {name}\u{2026}"),
        Msg::MatchingMultiple { shown, .. } => write!(o, "comprobando\u{2026} ({shown} dispositivos)"),
        Msg::Preparing => o.write_str("Preparando\u{2026}"),
        Msg::NoFleetKey => o.write_str("Este dispositivo aún no posee la clave de la flota.\nHazlo desde otro de tus dispositivos."),
        Msg::NoDeviceKey => o.write_str("La clave de este dispositivo aún no está lista. Intenta de nuevo en un momento."),
        Msg::AddingDevice(name) => write!(o, "Agregando {name}\u{2026}"),
        Msg::DeviceAdded => o.write_str("Dispositivo agregado \u{221a}"),
        Msg::JoinContended => o.write_str("Más de un dispositivo pide unirse, así que ahora solo se puede agregar uno que esté junto a este, por Bluetooth o NFC. Si estás agregando solo uno, alguien más conoce tu handle."),
        Msg::AddFromSignedIn => o.write_str("Agrega este dispositivo desde uno que ya esté dentro:"),
        Msg::AddDevicePill => o.write_str("Agregar dispositivo"),
        Msg::SelectedDevice(name) => write!(o, "Seleccionado: {name}"),
        Msg::IsNewDeviceGreen => o.write_str("\u{00BF}Tu nuevo dispositivo est\u{00E1} verde brillante?"),
        Msg::YesPill => o.write_str("S\u{00ED}"),
        Msg::NoPill => o.write_str("No"),
        Msg::AddLookFgtw => o.write_str("¿No está cerca? Busca a través de fgtw.org"),
        Msg::AddLookingFgtw => o.write_str("Buscando también a través de fgtw.org"),
        // ---- ferros's: adding a device ----
        Msg::DeviceAsksToJoin => o.write_str("un dispositivo en esta red pide unirse"),
        Msg::AddAsking => o.write_str("agregar dispositivo: dispositivos que piden unirse"),
        Msg::AddSelected => o.write_str("agregar dispositivo: seleccionado"),
        Msg::AddingToFleet => o.write_str("agregándolo a la flota"),
        Msg::HandingKey => o.write_str("entregándole la clave de la flota"),
        Msg::Added => o.write_str("agregado"),
        Msg::AddingFailed => o.write_str("no se pudo agregar"),
        Msg::CandAdded(name) => write!(o, "{name}  agregado"),
        Msg::CandNearby(name) => write!(o, "{name}  cerca: toca para seleccionar"),
        Msg::CandNotNearby(name) => write!(o, "{name}  lejos: escribe sus palabras"),
        Msg::OpenPhotonJoin => o.write_str("abre la pantalla para unirse de Photon en el dispositivo"),
        Msg::TypeItsWordsPill => o.write_str("escribir sus palabras"),
        Msg::HoldTogether => o.write_str("o junta los dos dispositivos: se une al instante"),
        Msg::DonePill => o.write_str("listo"),
        Msg::ClosePill => o.write_str("cerrar"),
        // ---- Photon's: the joining device ----
        Msg::SelectedBy(name) => write!(o, "Seleccionado por {name}"),
        Msg::JoinerSelected => o.write_str("¡Seleccionado!"),
        Msg::JoinerConfirmOther => o.write_str("Confirma en tu otro dispositivo para terminar."),
        Msg::LaunchJoinConfirmNote => o.write_str("Confirmarás la incorporación en ese dispositivo."),
        Msg::JoinAskFgtw => o.write_str("Mis dispositivos no están cerca: pedir a través de fgtw.org"),
        Msg::JoinAskedFgtw => o.write_str("Pedido a través de fgtw.org: escribe las palabras en tu otro dispositivo"),
        Msg::HandlesDontMatch => o.write_str("los dos no coinciden\ncorrige el nombre e inténtalo de nuevo"),
        Msg::DeviceBrandedHint => o.write_str("Este hardware sigue registrado en otra flota.\nQuien lo posee puede liberarlo con Liberar en su p\u{00E1}gina de Flota."),
        // ---- ferros's: the joining device ----
        Msg::UseExistingDevice => o.write_str("Usa un dispositivo que ya tengas para vincular este a tu flota."),
        Msg::WaitingFleetKeys => o.write_str("Esperando las claves de la flota."),
        Msg::BoundWaitingKeys => o.write_str("Vinculado a tu flota.\nEsperando sus claves."),
        Msg::DeniedBoundOther => o.write_str("Rechazado. Este dispositivo está vinculado a otra identidad."),
        Msg::OwnedByOther => o.write_str("Este dispositivo pertenece a otra identidad.\nSolo su flota puede liberarlo."),
        // ---- the fleet's devices ----
        Msg::ThisDevice => o.write_str("este dispositivo"),
        Msg::ADevice => o.write_str("un dispositivo"),
        Msg::TheDevice => o.write_str("el dispositivo"),
        Msg::OneOfYourDevices => o.write_str("uno de tus dispositivos"),
        Msg::MemberThisDevice(name) => write!(o, "{name}  este dispositivo"),
        Msg::MemberNearby(name) => write!(o, "{name}  cerca"),
        Msg::NoIdentityHere => o.write_str("no hay identidad aquí"),
        Msg::JoiningConfirm => o.write_str("uniéndose: confirma en uno de tus dispositivos"),
        Msg::InFleetWaitingKey => o.write_str("en la flota, esperando su clave"),
        Msg::InFleet => o.write_str("en la flota"),
        Msg::LeavingFleet => o.write_str("saliendo de la flota"),
        Msg::NewIdentityNoFleet => o.write_str("una identidad nueva: ninguna flota la tiene aún"),
        Msg::HandleHasOtherFleet => o.write_str("este handle tiene la flota de otra identidad"),
        Msg::NoVerdict => o.write_str("sin veredicto: nada responde"),
        Msg::LookingUp => o.write_str("buscando la identidad"),
        // ---- Photon's: leaving, on the other devices ----
        Msg::DepartureApproval(name) => write!(o, "{name} pide salir de tu flota. Apruébalo en Ajustes → Flota."),
        Msg::DepartRequestLine(name) => write!(o, "{name} pide salir de tu flota."),
        Msg::DepartFreesHardware => o.write_str("Aprobarlo lo borra y libera su hardware para que se una a cualquier flota."),
        Msg::DepartKeepsHardware => o.write_str("Aprobarlo lo borra.\nSu hardware sigue registrado en tu flota."),
        Msg::DepartApprovePill => o.write_str("Aprobar"),
        Msg::DepartDenyPill => o.write_str("Rechazar"),
        Msg::DepartDeniedHere(name) => write!(o, "Rechazado. {name} sigue en tu flota."),
        Msg::DepartComplete(n) => write!(o, "{n} sali\u{00F3} de tu flota.\nSu hardware est\u{00E1} libre."),
        Msg::FleetSignedOut(name) => write!(o, "{name} sali\u{f3} de la flota."),
        Msg::DepartReleasePending(n) => write!(o, "{n} sali\u{00F3} de tu flota, pero su hardware no se liber\u{00F3}.\nUsa Liberar en su fila retirada para reintentar."),
        Msg::DeviceReleased(name) => write!(o, "{name} liberado.\nAhora puede unirse a cualquier flota."),
        // ---- ferros's: leaving, on the other devices ----
        Msg::DepartDenyKeeps => o.write_str("rechazar lo mantiene en tu flota"),
        Msg::DepartApproveAgainPill => o.write_str("aprobar de nuevo: la última no salió"),
        Msg::DepartApproving => o.write_str("aprobando"),
        Msg::DepartApproved => o.write_str("aprobado: está saliendo de tu flota"),
        // ---- Photon's: leaving, this device ----
        Msg::DepartWaitingLine => o.write_str("Pidiendo a tus otros dispositivos que dejen salir a este. Apruébalo en cualquiera de ellos."),
        Msg::DepartDenied => o.write_str("Uno de tus dispositivos rechazó esta solicitud, así que este dispositivo sigue en tu flota. Pulsa Liberar para pedirlo de nuevo."),
        // ---- ferros's: leaving, this device ----
        Msg::RemovePill { armed } => o.write_str(if armed { "toca otra vez: quitar este dispositivo" } else { "quitar este dispositivo" }),
        Msg::DepartAsking => o.write_str("este dispositivo pide a tu flota que lo libere"),
        Msg::DepartSending => o.write_str("enviando la solicitud a tus dispositivos"),
        Msg::DepartTapHint => o.write_str("aprueba o rechaza en cualquiera de tus otros dispositivos,\no junta uno de ellos con este"),
        Msg::DepartThen => o.write_str("una vez aprobado, tus cosas se borran de él\ny se reinicia; atrás cancela la salida"),
        Msg::DepartDeniedOn(name) => write!(o, "la salida fue rechazada en {name}"),
        Msg::DepartNotStarted => o.write_str("la salida no comenzó"),
    }
}
